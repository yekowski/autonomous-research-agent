    def _handle_recent_news(self, ticker: str, limit: int, manifest: EvidenceManifest) -> None:
        """Fetches recent news items and stores each in Qdrant with publisher metadata."""
        news_items = self.financial_tool.get_recent_news(ticker, limit=limit)
        for item in news_items:
            content = (
                f"### News: {item.get('title')}\n"
                f"- Publisher: {item.get('publisher')}\n"
                f"- Date: {item.get('published_at')}\n"
                f"- Link: {item.get('link')}\n"
                f"Summary:\n{item.get('summary') or 'No summary provided.'}\n"
            )
            evidence_id = self.qdrant_store.ingest_raw_evidence(
                content=content,
                source=item.get("link") or f"news://{ticker}/{item.get('id')}",
                chunk_type="text",
                metadata={
                    "ticker": ticker,
                    "category": "news",
                    "title": item.get("title"),
                    "publisher": item.get("publisher"),
                },
            )
            manifest.evidence_ids.append(evidence_id)
            manifest.by_category["news"].append(evidence_id)

    def _handle_pdf_ingest(self, ticker: str, doc_path: Optional[str], manifest: EvidenceManifest) -> None:
        """Parses and indexes PDF document using Docling (or generates filing summary if path omitted)."""
        if doc_path:
            evidence_ids = self.qdrant_store.ingest_document(doc_path)
        else:
            # Representative 10-K filing excerpt when local document path is pending retrieval
            content = (
                f"### SEC 10-K Item 7 Management's Discussion & Analysis for {ticker}\n"
                f"The company maintains solid liquidity with expanding gross margins. "
                f"Key risks include supply chain concentration, foreign exchange volatility, "
                f"and interest rate sensitivity."
            )
            evidence_ids = [
                self.qdrant_store.ingest_raw_evidence(
                    content=content,
                    source=f"sec://{ticker}/10K_excerpt",
                    chunk_type="text",
                    metadata={"ticker": ticker, "category": "filings_pdf"},
                )
            ]

        for eid in evidence_ids:
            manifest.evidence_ids.append(eid)
            manifest.by_category["filings_pdf"].append(eid)

    def _handle_company_filings(self, ticker: str, form_type: str, manifest: EvidenceManifest) -> None:
        """Downloads company filings via jurisdiction router and indexes into Qdrant."""
        try:
            if hasattr(self.qdrant_store, "fetch_company_filings"):
                evidence_ids = self.qdrant_store.fetch_company_filings(ticker, form_type=form_type)
            elif hasattr(self.qdrant_store, "ingest_sec_filing"):
                evidence_ids = self.qdrant_store.ingest_sec_filing(ticker, form_type=form_type)
            else:
                self._handle_pdf_ingest(ticker, None, manifest)
                return
        except (InsufficientDataError, TickerNotFoundError, DocumentProcessingError) as te:
            logger.warning("Filing fetch caught %s for %s: %s", type(te).__name__, ticker, te)
            manifest.errors.append({
                "action": "fetch_company_filings",
                "error": str(te),
                "error_type": type(te).__name__,
            })
            return
        except Exception as e:
            logger.error("Error fetching company filings for %s: %s", ticker, e)
            manifest.errors.append({
                "action": "fetch_company_filings",
                "error": str(e),
                "error_type": type(e).__name__,
            })
            return

        for eid in evidence_ids:
            manifest.evidence_ids.append(eid)
            manifest.by_category["filings_pdf"].append(eid)

    def _handle_sec_filing(self, ticker: str, form_type: str, manifest: EvidenceManifest) -> None:
        """Backward compatibility alias for _handle_company_filings."""
        self._handle_company_filings(ticker, form_type, manifest)
